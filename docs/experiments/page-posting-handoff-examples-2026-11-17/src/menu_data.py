def menu_cost(menu):
    """메뉴 1개의 원가(원)와 분류별 합."""
    by = {"식재료": 0.0, "포장·일회용품": 0.0, "기타 변동비": 0.0}
    for key, qty in menu["lines"]:
        ing = ING[key]
        by[ing[5]] += ing[4] * qty
    for _name, rate, _src in menu["pct"]:
        by["기타 변동비"] += menu["price"] * rate
    return sum(by.values()), by


def tier_summary(ind, tier_key, rent=DEFAULT_RENT):
    t = ind["tiers"][tier_key]
    tot_share = sum(mm["share"] for mm in t["menus"])
    avg_price = sum(mm["price"] * mm["share"] for mm in t["menus"]) / tot_share
    avg_cost = sum(menu_cost(mm)[0] * mm["share"] for mm in t["menus"]) / tot_share
    rate = avg_cost / avg_price
    labor = t["staff"] * WAGE * PAID_HOURS / 10000  # 만원
    fixed = rent + labor + ind["other_fixed"]
    bep = fixed / (1 - rate)                         # 만원/월
    daily_units = bep * 10000 / avg_price / ind["days"]
    setup = sum(q * p for _n, _c, q, p in t["setup"]) / 10000  # 만원
    return {"avg_price": avg_price, "cost_rate": rate, "labor": labor, "fixed": fixed, "bep": bep,
            "daily_units": daily_units, "setup_man": setup, "menus": len(t["menus"]), "staff": t["staff"]}


